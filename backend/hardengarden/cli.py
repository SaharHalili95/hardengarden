app = typer.Typer(
    name="hardengarden",
    help="AI-assisted, read-only Linux hardening auditor.",
    no_args_is_help=True,
    add_completion=False,
    pretty_exceptions_enable=False,
)

_STATUS_COLORS = {
    Status.PASS: typer.colors.GREEN,
    Status.FAIL: typer.colors.RED,
    Status.WARN: typer.colors.YELLOW,
    Status.ERROR: typer.colors.MAGENTA,
    Status.SKIPPED: typer.colors.BLUE,
    Status.NOT_APPLICABLE: typer.colors.WHITE,
}
_STATUS_LABEL = {Status.NOT_APPLICABLE: "N/A"}


def _version(value: bool) -> None:
    if value:
        typer.echo(f"hardengarden {__version__}")
        raise typer.Exit


@app.callback()
def main(
    version: Annotated[
        bool, typer.Option("--version", callback=_version, is_eager=True, help="Show the version.")
    ] = False,
) -> None:
    """HardenGarden: your system is a garden; HardenGarden finds the weeds."""
    _ = version


def render_text(report: ScanReport, checks: tuple[Check, ...]) -> str:
    metas = {c.meta.id: c.meta for c in checks}
    lines: list[str] = []
    support = "supported" if report.platform_supported else "UNSUPPORTED"
    lines.append(f"HardenGarden {report.tool_version} · {report.platform.pretty_name} ({support})")
    lines.append(f"Scanned root: {report.scanned_root}")
    if not report.platform_supported:
        lines.append(
            "Notice: unsupported platform. Platform-specific checks are marked N/A; "
            "supported: Ubuntu 22.04, Ubuntu 24.04, Debian 12."
        )
    lines.append("")
    for result in report.results:
        meta = metas[result.check_id]
        label = _STATUS_LABEL.get(result.status, result.status.value)
        status = typer.style(f"{label:<7}", fg=_STATUS_COLORS[result.status], bold=True)
        lines.append(f"  {status} {meta.severity.value:<8} {meta.id}  {meta.title}")
        for item in result.evidence:
            lines.append(f"           {item}")
        if result.reason:
            lines.append(f"           reason: {result.reason}")
    summary = report.summary
    cov = summary.coverage
    score = "Not enough data" if summary.score is None else f"{summary.score}/100"
    percent = "n/a" if cov.percent is None else f"{cov.percent}%"
    lines.append("")
    lines.append(f"Garden Health: {score}")
    lines.append(
        f"Coverage: {cov.evaluated} evaluated ({percent}) · {cov.skipped} skipped · "
        f"{cov.errors} error(s) · {cov.not_applicable} not applicable"
    )
    if report.privilege_hint:
        lines.append(typer.style(report.privilege_hint, fg=typer.colors.YELLOW))
    return "\n".join(lines)


@app.command()
def scan(
    json_output: Annotated[bool, typer.Option("--json", help="Print the report as JSON.")] = False,
    root: Annotated[
        Path,
        typer.Option(
            "--root",
            help="Filesystem root to scan (default /). Commands only run when scanning /.",
            file_okay=False,
            dir_okay=True,
        ),
    ] = Path("/"),
) -> None:
    """Scan this machine with read-only checks and print the findings."""
    try:
        view = SystemView(root)
    except SystemViewError as exc:
        typer.echo(f"error: {exc}", err=True)
        raise typer.Exit(code=2) from exc
    report = run_scan(view, ALL_CHECKS)
    if json_output:
        typer.echo(report.model_dump_json(indent=2))
    else:
        typer.echo(render_text(report, ALL_CHECKS))


def render_checks_markdown(checks: tuple[Check, ...]) -> str:
    lines = [
        "# Checks",
        "",
        "<!-- Generated by `hardengarden checks --markdown`. Do not edit by hand. -->",
        "",
        'All checks are read-only. "Root" means the check is SKIPPED without root on a live host.',
        "",
        "| ID | Title | Category | Severity | Root | Platforms | Remediation |",
        "|---|---|---|---|---|---|---|",
    ]
    for check in checks:
        m = check.meta
        platforms = ", ".join(m.platforms)
        template = f"`{m.remediation_template}`" if m.remediation_template else "guidance only"
        root = "yes" if m.requires_root else "no"
        lines.append(
            f"| {m.id} | {m.title} | {m.category.value} | {m.severity.value} | {root} "
            f"| {platforms} | {template} |"
        )
    lines.append("")
    lines.append("## Rationale")
    lines.append("")
    for check in checks:
        m = check.meta
        lines.append(f"- **{m.id}**: {m.rationale} Knowledge base: `{m.kb_doc}`.")
    lines.append("")
    return "\n".join(lines)


@app.command()
def checks(
    markdown: Annotated[bool, typer.Option("--markdown", help="Print as Markdown.")] = False,
) -> None:
    """List all checks."""
    if markdown:
        typer.echo(render_checks_markdown(ALL_CHECKS), nl=False)
        return
    for check in ALL_CHECKS:
        m = check.meta
        typer.echo(f"{m.id:<11} {m.severity.value:<8} {m.title}")


kb_app = typer.Typer(help="Knowledge base: ingest, search and evaluate.", no_args_is_help=True)
app.add_typer(kb_app, name="kb")


@kb_app.command("ingest")
def kb_ingest(
    with_manpages: Annotated[
        bool,
        typer.Option("--with-manpages", help="Also index this system's man pages (local only)."),
    ] = False,
) -> None:
    """Build the local search index. Uses Ollama embeddings when available."""
    summary = KnowledgeService(load_settings()).ingest(with_manpages=with_manpages)
    typer.echo(f"Knowledge base version {summary.kb_version}: {summary.lexical_chunks} chunks")
    if with_manpages:
        typer.echo(f"Man pages: {summary.manpage_chunks} chunks from this system")
    for report in summary.vector_reports:
        typer.echo(
            f"Vectors [{report.collection}]: +{report.added} added, {report.updated} updated, "
            f"{report.removed} removed, {report.unchanged} unchanged in {report.seconds}s"
        )
    if summary.vectors_skipped_reason:
        typer.echo(summary.vectors_skipped_reason)


@kb_app.command("search")
def kb_search(
    question: Annotated[str, typer.Argument(help="A question in plain language.")],
) -> None:
    """Show which knowledge-base passages a question retrieves, and whether it is answerable."""
    result = KnowledgeService(load_settings()).retriever().search(question)
    verdict = "answerable" if result.answerable else "not enough information"
    mode = "keyword + vector" if result.used_vectors else "keyword only"
    typer.echo(
        f"{verdict} (confidence {result.confidence:.2f}, threshold {result.threshold:.2f}, {mode})"
    )
    for hit in result.hits:
        typer.echo(f"  {hit.passage.id}")


@kb_app.command("eval")
def kb_eval(
    golden: Annotated[Path, typer.Argument(help="Golden YAML file.", exists=True, dir_okay=False)],
    vectors: Annotated[
        bool, typer.Option("--vectors/--no-vectors", help="Use the vector index.")
    ] = True,
) -> None:
    """Print Recall@5 and negative rejection for a golden set."""
    retriever = KnowledgeService(load_settings()).retriever(use_vectors=vectors)
    report = evaluate(retriever, load_golden(golden))
    typer.echo(f"Mode: {'keyword + vector' if report.used_vectors else 'keyword only'}")
    typer.echo(f"Recall@5: {report.recall_at_5:.4f} ({report.answerable} answerable questions)")
    typer.echo(f"Negative rejection: {report.negative_rejection:.4f} ({report.negative} questions)")
    for line in report.misses:
        typer.echo(f"  miss: {line}")
    for line in report.false_accepts:
        typer.echo(f"  false accept: {line}")


def _assistant() -> Assistant:
    settings = load_settings()
    return Assistant(settings, KnowledgeService(settings))


def _print_answer(result: Generation | Answer) -> int:
    """Stream a generation (or print an immediate answer). Returns the exit code."""
    if isinstance(result, Generation):
        streamed = False
        try:
            for delta in result:
                typer.echo(delta, nl=False)
                streamed = True
        except KeyboardInterrupt:
            result.cancel()
        answer = result.answer or Answer(Outcome.CANCELLED, "Stopped.")
        if streamed:
            typer.echo("")
        if answer.outcome is not Outcome.ANSWERED:
            typer.echo(answer.text)
    else:
        answer = result
        typer.echo(answer.text)
    if answer.citations:
        typer.echo("Sources: " + ", ".join(answer.citations))
    if answer.cached:
        typer.echo("(cached answer)")
    return 0 if answer.outcome in {Outcome.ANSWERED, Outcome.NOT_ENOUGH_INFORMATION} else 1


@app.command()
def explain(
    check_id: Annotated[str, typer.Argument(help="Check ID, for example HG-SSH-001.")],
    root: Annotated[
        Path, typer.Option("--root", help="Filesystem root to scan.", file_okay=False)
    ] = Path("/"),
    no_cache: Annotated[bool, typer.Option("--no-cache", help="Ignore cached answers.")] = False,
) -> None:
    """Explain one finding in plain language, grounded in the knowledge base."""
    check = next((c for c in ALL_CHECKS if c.meta.id == check_id.upper()), None)
    if check is None:
        typer.echo(f"error: unknown check {check_id!r}; see 'hardengarden checks'", err=True)
        raise typer.Exit(code=2)
    try:
        view = SystemView(root)
    except SystemViewError as exc:
        typer.echo(f"error: {exc}", err=True)
        raise typer.Exit(code=2) from exc
    report = run_scan(view, (check,))
    result = report.results[0]
    typer.echo(f"{check.meta.id} {check.meta.title}: {result.status.value}")
    script = render(check.meta)
    if script is not None and result.status.value in {"FAIL", "WARN"}:
        typer.echo(
            f"Remediation script: 'hardengarden remediation {check.meta.id}' "
            "(review before running; it is a dry run unless HG_APPLY=1)."
        )
    raise typer.Exit(
        code=_print_answer(_assistant().explain(check, result, use_cache=not no_cache))
    )


@app.command()
def ask(question: Annotated[str, typer.Argument(help="A question about Linux hardening.")]) -> None:
    """Ask a question; the answer is grounded in the knowledge base or refused."""
    raise typer.Exit(code=_print_answer(_assistant().chat(question)))


@app.command()
def remediation(check_id: Annotated[str, typer.Argument(help="Check ID.")]) -> None:
    """Print the vetted remediation script for a check (HardenGarden never runs it)."""
    check = next((c for c in ALL_CHECKS if c.meta.id == check_id.upper()), None)
    if check is None:
        typer.echo(f"error: unknown check {check_id!r}", err=True)
        raise typer.Exit(code=2)
    script = render(check.meta)
    if script is None:
        typer.echo(
            f"{check.meta.id} has no script: the fix depends on the service. See its guidance."
        )
        raise typer.Exit(code=1)
    typer.echo(script, nl=False)


ai_app = typer.Typer(help="Local AI model status and downloads.", no_args_is_help=True)
app.add_typer(ai_app, name="ai")


@ai_app.command("status")
def ai_status() -> None:
    """Show the hardware tier, the selected model and whether explanations are available."""
    status = _assistant().status()
    data = status.to_dict()
    typer.echo(f"State: {data['state']}  Tier: {data['tier']}  Model: {data['model'] or '-'}")
    mem = status.hardware.memory
    if mem is not None:
        total, free = mem.total_bytes / 1024**3, mem.available_bytes / 1024**3
        typer.echo(f"RAM: {total:.1f} GiB total, {free:.1f} GiB free")
    gpu = {True: "yes", None: "unknown"}.get(status.hardware.gpu, "no")
    typer.echo(f"CPU cores: {status.hardware.cpu_cores}  GPU: {gpu}")
    typer.echo(status.message)


@ai_app.command("pull")
def ai_pull(
    model: Annotated[str, typer.Argument(help="Model name from the catalog.")],
    yes: Annotated[
        bool, typer.Option("--yes", help="Confirm the download without a prompt.")
    ] = False,
) -> None:
    """Download a model through Ollama, only after explicit confirmation (R37)."""
    info = CATALOG.get(model)
    if info is None:
        typer.echo(f"error: unknown model {model!r}; choose one of {sorted(CATALOG)}", err=True)
        raise typer.Exit(code=2)
    size = f"about {info.download_bytes / 1e9:.1f} GB"
    consent = yes or typer.confirm(f"Download {info.name} ({size}) through Ollama?", default=False)
    if not consent:
        typer.echo("Nothing downloaded.")
        raise typer.Exit(code=1)
    settings = load_settings()
    try:
        pull = start_pull(OllamaClient(settings.ollama_url), info.name, consent=True)
        last = ""
        for progress in pull:
            line = progress.status
            if progress.total:
                line += f" {100 * (progress.completed or 0) // progress.total}%"
            if line != last:
                typer.echo(line)
                last = line
    except OllamaError as exc:
        typer.echo(f"error: {exc}", err=True)
        raise typer.Exit(code=1) from exc
    except KeyboardInterrupt:
        pull.cancel()
        typer.echo("Cancelled. Running the same command again resumes the download.")
        raise typer.Exit(code=1) from None


